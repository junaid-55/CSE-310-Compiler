NEW_LINE proc
	PUSH AX
	PUSH DX
	MOV AH,2
	MOV DL,0Dh
	INT 21h
	MOV AH,2
	MOV DL,0Ah
	INT 21h
	POP DX
	POP AX
	RET
NEW_LINE ENDP
PRINT_OUTPUT proc  ;print what is in ax
	PUSH AX
	PUSH BX
	PUSH CX
	PUSH DX
	PUSH SI
	LEA SI,NUMBER
	MOV BX,10
	ADD SI,4
	CMP AX,0
	JGE print
	PUSH AX
	MOV AH,2
	MOV DL,'-'
	INT 21h
	POP AX
	NEG AX
PRINT:
	XOR DX,DX
	DIV BX
	MOV [SI],DL
	ADD [SI],'0'
	DEC SI
	CMP AX,0
	JNE PRINT
	INC SI
	LEA DX,SI
	MOV AH,9
	INT 21h
	POP SI
	POP DX
	POP CX
	POP BX
	POP AX
	RET
PRINT_OUTPUT ENDP
